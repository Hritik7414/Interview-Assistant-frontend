import type { ProviderDescriptor } from '@shared';
import { Bot, FlaskConical } from 'lucide-react';
import { Badge } from '@/components/ui/badge';

/** Makes it explicit whether content came from a real provider or a simulation. */
export function ProviderBadge({
  provider,
  kind,
}: {
  provider: ProviderDescriptor;
  kind: 'transcript' | 'answer';
}) {
  if (provider.simulated) {
    return (
      <Badge
        variant="warning"
        title={`This ${kind} is simulated by Demo Mode — no external AI provider was called.`}
      >
        <FlaskConical aria-hidden />
        Simulated {kind}
      </Badge>
    );
  }
  return (
    <Badge
      variant="outline"
      title={`Generated by ${provider.name}${provider.model ? ` (${provider.model})` : ''}`}
    >
      <Bot aria-hidden />
      {provider.model ?? provider.name}
    </Badge>
  );
}
